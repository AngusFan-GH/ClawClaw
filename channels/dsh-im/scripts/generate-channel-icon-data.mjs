import { readFile, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'

const root = new URL('../client/assets/channel-icons/', import.meta.url)
const sources = JSON.parse(await readFile(new URL('sources.json', root), 'utf8'))
const data = {}
for (const [channel, source] of Object.entries(sources)) {
  const bytes = await readFile(new URL(source.file, root))
  if (createHash('sha256').update(bytes).digest('hex') !== source.sha256) {
    throw new Error(`Official channel icon checksum mismatch: ${channel}`)
  }
  data[channel] = `data:${source.mime};base64,${bytes.toString('base64')}`
}
await writeFile(new URL('../client/channel-icon-data.js', import.meta.url),
  '// Generated by scripts/generate-channel-icon-data.mjs. Original vendor bytes.\n'
  + `export const OFFICIAL_CHANNEL_ICON_DATA = Object.freeze(${JSON.stringify(data, null, 2)})\n`)
