import fs from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const workspaceRoot = process.cwd();

async function findOpenClawRegistryModule(rootDir) {
  const pnpmDir = path.join(rootDir, 'node_modules', '.pnpm');
  const entries = await fs.readdir(pnpmDir, { withFileTypes: true });
  const openclawEntry = entries
    .filter((entry) => entry.isDirectory() && entry.name.startsWith('openclaw@'))
    .sort((a, b) => b.name.localeCompare(a.name))[0];

  if (!openclawEntry) {
    throw new Error('Unable to locate pnpm openclaw package directory.');
  }

  const distDir = path.join(
    pnpmDir,
    openclawEntry.name,
    'node_modules',
    'openclaw',
    'dist',
  );
  const distEntries = await fs.readdir(distDir);
  const registryFile = distEntries.find(
    (file) => file.startsWith('commands-registry-') && file.endsWith('.js'),
  );

  if (!registryFile) {
    throw new Error(`Unable to locate commands registry bundle in ${distDir}`);
  }

  return path.join(distDir, registryFile);
}

function simplifyChoice(choice) {
  if (typeof choice === 'string') {
    return choice;
  }
  if (choice && typeof choice === 'object' && typeof choice.value === 'string') {
    return { value: choice.value, label: typeof choice.label === 'string' ? choice.label : choice.value };
  }
  return null;
}

function simplifyArg(arg) {
  if (!arg || typeof arg !== 'object') {
    return null;
  }

  const choices = Array.isArray(arg.choices)
    ? arg.choices.map(simplifyChoice).filter(Boolean)
    : undefined;

  return {
    name: String(arg.name),
    description: String(arg.description ?? ''),
    required: Boolean(arg.required),
    captureRemaining: Boolean(arg.captureRemaining),
    choices: choices?.length ? choices : undefined,
  };
}

function simplifyCommand(command) {
  return {
    key: String(command.key),
    description: String(command.description ?? ''),
    textAliases: Array.isArray(command.textAliases)
      ? command.textAliases.map((alias) => String(alias))
      : [],
    acceptsArgs: Boolean(command.acceptsArgs),
    category: typeof command.category === 'string' ? command.category : undefined,
    args: Array.isArray(command.args)
      ? command.args.map(simplifyArg).filter(Boolean)
      : undefined,
  };
}

function renderModule(commands) {
  const payload = JSON.stringify(commands, null, 2);
  return `/* eslint-disable */
// Generated by scripts/sync-openclaw-chat-commands.mjs
// Source: installed openclaw package in node_modules

export type GeneratedOpenClawArgChoice = string | { value: string; label: string };

export type GeneratedOpenClawArgDefinition = {
  name: string;
  description: string;
  required?: boolean;
  captureRemaining?: boolean;
  choices?: GeneratedOpenClawArgChoice[];
};

export type GeneratedOpenClawCommandDefinition = {
  key: string;
  description: string;
  textAliases: string[];
  acceptsArgs?: boolean;
  category?: string;
  args?: GeneratedOpenClawArgDefinition[];
};

export const GENERATED_OPENCLAW_CHAT_COMMANDS: GeneratedOpenClawCommandDefinition[] = ${payload} as const;
`;
}

async function main() {
  const modulePath = await findOpenClawRegistryModule(workspaceRoot);
  const mod = await import(pathToFileURL(modulePath).href);
  if (typeof mod.c !== 'function') {
    throw new Error(`Expected listChatCommands export "c" in ${modulePath}`);
  }
  const commands = mod.c().map(simplifyCommand);
  const outputPath = path.join(
    workspaceRoot,
    'src',
    'pages',
    'Chat',
    'openclaw-command-catalog.generated.ts',
  );
  await fs.writeFile(outputPath, renderModule(commands), 'utf8');
  console.log(`Wrote ${commands.length} OpenClaw chat commands to ${outputPath}`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
